import {mkdir,copyFile,writeFile,readFile} from "node:fs/promises";
import {resolve,dirname} from "node:path";
import {execFileSync} from "node:child_process";
import {createHash} from "node:crypto";
import assert from "node:assert/strict";
import {collectSource,fileManifest} from "./source-files.mjs";
const root=process.cwd(),source=await collectSource(root),manifest=await fileManifest(root,source.files),staging=resolve(".cache",`source-delivery-${Date.now()}`);
const androidGradle=await readFile(resolve(root,"android/app/build.gradle.kts"),"utf8");
const appVersion=androidGradle.match(/versionName\s*=\s*"([^"]+)"/)?.[1];
const versionCode=Number(androidGradle.match(/versionCode\s*=\s*(\d+)/)?.[1]);
assert.ok(appVersion&&Number.isInteger(versionCode),"Android app version metadata must be present");
await mkdir(staging,{recursive:true});
for(const path of source.files){await mkdir(dirname(resolve(staging,path)),{recursive:true});await copyFile(resolve(root,path),resolve(staging,path));}
const report={createdAtUtc:new Date().toISOString(),appVersion,versionCode,head:source.head,origin:source.origin,containsUncommittedWorkingFiles:true,personalAcademicReportIncluded:false,ignoredTracked:source.ignoredTracked,unsafeTracked:source.unsafeTracked,...manifest};
await writeFile(resolve(staging,"SOURCE_MANIFEST.json"),JSON.stringify(report,null,2));await mkdir("releases",{recursive:true});
const archive=resolve(`releases/danpan-omok-android-${appVersion}-source.tar.gz`);execFileSync("tar",["-czf",archive,"-C",staging,"."],{stdio:"pipe"});
const listed=execFileSync("tar",["-tzf",archive],{encoding:"utf8"}).split(/\r?\n/).filter(p=>p&&!p.endsWith("/")).map(p=>p.replace(/^\.\//,""));
assert.deepEqual(listed.sort(),[...source.files,"SOURCE_MANIFEST.json"].sort());
const sha256=createHash("sha256").update(await readFile(archive)).digest("hex"),archiveName=archive.split(/[\\/]/).at(-1);
await writeFile("releases/SHA256SUMS.txt",`${sha256}  ${archiveName}\n`);await writeFile("releases/source-manifest.json",JSON.stringify(report,null,2));
console.log(JSON.stringify({archive,sha256,files:source.files.length,codeSha256:manifest.codeSha256,privateReportIncluded:false}));
